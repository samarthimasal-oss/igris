import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import sharp from 'sharp'
import pngToIco from 'png-to-ico'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const build = join(root, 'build')
const svg = await readFile(join(build, 'icon.svg'))
await mkdir(build, { recursive: true })

const sizes = [16, 24, 32, 48, 64, 128, 256, 512]
const pngPaths = []
for (const size of sizes) {
  const target = join(build, `icon-${size}.png`)
  await sharp(svg, { density: 420 }).resize(size, size).png().toFile(target)
  pngPaths.push(target)
}
await sharp(svg, { density: 420 }).resize(256, 256).png().toFile(join(build, 'icon.png'))

const ico = await pngToIco([16, 24, 32, 48, 64, 128, 256].map((size) => join(build, `icon-${size}.png`)))
await writeFile(join(build, 'icon.ico'), ico)

await sharp(svg, { density: 420 }).resize(32, 32).png().toFile(join(build, 'tray.png'))
const trayBase64 = (await readFile(join(build, 'tray.png'))).toString('base64')
await writeFile(
  join(root, 'src/main/trayIcon.ts'),
  `// Generated by scripts/generate-icons.mjs\nexport const TRAY_ICON_PNG =\n  '${trayBase64}'\n`,
  'utf8'
)

console.log('Generated icon.ico, PNG sizes, icon.png and src/main/trayIcon.ts')
